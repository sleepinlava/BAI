def test_snakemake_exporter_renders_rules_from_abi_plan(tmp_path):
    plugin = get_plugin("metatranscriptomics")
    config = plugin.load_config(
        overrides={
            "outdir": str(tmp_path / "results"),
            "log_dir": str(tmp_path / "log"),
        }
    )
    plan = plugin.build_plan(config)

    script = SnakemakeExporter().export(plan, config, plugin.registry())

    assert script.startswith("# Generated by ABI SnakemakeExporter.")
    assert "rule all:" in script
    assert "rule RNA1_QC_FASTP:" in script
    assert "rule RNA1_ALIGNMENT_STAR:" in script
    assert "rule RNA1_EXPRESSION_FEATURECOUNTS:" in script
    assert "fastp -i" in script
    assert "/examples/fixtures/tiny_R1.fastq" in script
    assert "STAR --runThreadN 4" in script
    assert 'featureCounts -T "$1" -p' in script
    assert "retrying featureCounts without -p" in script


