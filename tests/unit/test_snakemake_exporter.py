def test_size_to_mb_conversions():
    assert _size_to_mb("16GB") == 16384
    assert _size_to_mb("500MB") == 500
    assert _size_to_mb("1TB") == 1048576
    assert _size_to_mb("bogus") is None


def test_walltime_to_minutes_conversions():
    assert _walltime_to_minutes("04:00:00") == 240
    assert _walltime_to_minutes("01:30:00") == 90
    assert _walltime_to_minutes("45") == 45
    assert _walltime_to_minutes("bogus") is None
