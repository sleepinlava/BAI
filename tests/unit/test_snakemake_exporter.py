def test_snakemake_exporter_preserves_existing_snakefile_when_export_fails(tmp_path):
    output = tmp_path / "Snakefile"
    output.write_text("old workflow\n", encoding="utf-8")
    bad_step = PlanStep("bad", "Bad", "missing", "test")
    plan = SimpleNamespace(analysis_type="test", project_name="test", threads=1, steps=[bad_step])

    with pytest.raises(ToolError, match="unknown tool"):
        SnakemakeExporter().write(plan, {}, ToolRegistry([]), output)

    assert output.read_text(encoding="utf-8") == "old workflow\n"


def test_snakemake_worker_internal_rule_payload_matches_step_runner_contract(tmp_path, monkeypatch):
    step = PlanStep(
        "normalize",
        "Normalize",
        "internal",
        "normalization",
        inputs={"source": "input.tsv"},
        outputs={"output_dir": str(tmp_path / "normalized")},
        params={
            "threshold": 2,
            "_internal_handler": {
                "handler_id": "normalize",
                "execution_scope": "worker",
            },
        },
    )
    plan = SimpleNamespace(
        analysis_type="example_plugin", project_name="test", threads=1, steps=[step]
    )
    config = {"outdir": str(tmp_path / "results"), "feature": {"enabled": True}}

    script = SnakemakeExporter().export(plan, config, ToolRegistry([]), project_root=tmp_path)

    assert "rule NORMALIZE:" in script
    assert '"plugin_id": "example_plugin"' in script
    assert '"step_name": "Normalize"' in script
    assert "chmod 600 .abi_payload.json" in script
    assert "abi run-step --payload-file .abi_payload.json" in script

    payload_match = re.search(
        r"<<'ABI_PAYLOAD'\n(?P<payload>.*?)\nABI_PAYLOAD", script, flags=re.DOTALL
    )
    assert payload_match is not None
    # Braces are doubled for Snakemake shell substitution; undo before parsing.
    payload = json.loads(payload_match.group("payload").replace("{{", "{").replace("}}", "}"))
    assert set(payload) == {
        "plugin_id",
        "step",
        "config",
        "provenance_dir",
        "result_path",
    }

    from abi import step_runner

    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(step_runner, "get_plugin", lambda plugin_id: object())
    monkeypatch.setattr(
        step_runner,
        "execute_step",
        lambda plugin, actual_step, actual_config, provenance_dir: step_runner.StepExecutionResult(
            step_id=actual_step.step_id,
            tool_id=actual_step.tool_id,
            status="success",
        ),
    )
    payload_path = tmp_path / ".abi_payload.json"
    payload_path.write_text(json.dumps(payload), encoding="utf-8")

    result = step_runner.execute_step_payload(payload_path)

    assert result.status == "success"
    assert (tmp_path / ".abi_result.json").exists()


