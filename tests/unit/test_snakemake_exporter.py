def test_snakemake_exporter_escapes_literal_braces_in_shell(tmp_path):
    step = PlanStep(
        "brace",
        "Brace",
        "fake_tool",
        "test",
        outputs={"output_dir": str(tmp_path / "out")},
    )
    plan = SimpleNamespace(analysis_type="test", project_name="test", threads=1, steps=[step])
    registry = ToolRegistry([])

    class _BraceSkill:
        def build_command(self, params):
            return ["sh", "-c", "echo ${UNSET_VAR:-default}"]

    registry.has = lambda tool_id: True  # type: ignore[method-assign]
    registry.create = lambda tool_id, mock_tools=True: _BraceSkill()  # type: ignore[method-assign]
    registry.get = lambda tool_id: {}  # type: ignore[method-assign]

    script = SnakemakeExporter().export(plan, {"outdir": str(tmp_path)}, registry)

    assert "${{UNSET_VAR:-default}}" in script


