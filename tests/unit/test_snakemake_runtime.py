def test_snakemake_dry_run_writes_snakefile_and_provenance_without_executing(
    tmp_path, monkeypatch
) -> None:
    plugin = get_plugin("metatranscriptomics")
    config = plugin.load_config(overrides={"outdir": str(tmp_path / "results")})
    plan = plugin.build_plan(config)
    runtime = SnakemakeRuntime(plugin, options=RuntimeOptions(engine="snakemake", smoke=True))

    def _forbidden(*args, **kwargs):  # pragma: no cover - must never run
        raise AssertionError("dry_run must not execute snakemake")

    monkeypatch.setattr(subprocess, "run", _forbidden)
    result = runtime.dry_run(plan, config)

    assert result.status == "dry_run"
    assert result.return_code == 0
    snakefile = result.outputs["snakefile"]
    assert snakefile.exists()
    assert snakefile.read_text(encoding="utf-8").startswith("# Generated by ABI SnakemakeExporter.")
    assert (tmp_path / "results" / "provenance" / "commands.tsv").exists()
    assert (tmp_path / "results" / "execution_plan.json").exists()
    # No snakemake logs: nothing was executed.
    assert not (tmp_path / "results" / "snakemake" / "snakemake.stdout.log").exists()


def test_snakemake_run_success_writes_logs_and_provenance(tmp_path) -> None:
    plugin = get_plugin("metatranscriptomics")
    config = plugin.load_config(overrides={"outdir": str(tmp_path / "results")})
    plan = plugin.build_plan(config)
    fake_bin = _fake_snakemake(tmp_path, exit_code=0)
    runtime = SnakemakeRuntime(
        plugin,
        options=RuntimeOptions(engine="snakemake", smoke=True, snakemake_bin=fake_bin),
    )

    result = runtime.run(plan, config)

    assert result.status == "success"
    assert result.return_code == 0
    assert result.outputs["snakefile"].exists()
    assert result.outputs["snakemake_stdout"].exists()
    assert result.outputs["snakemake_stderr"].exists()
    commands_tsv = (tmp_path / "results" / "provenance" / "commands.tsv").read_text(
        encoding="utf-8"
    )
    assert "success" in commands_tsv


def test_snakemake_run_failure_writes_provenance_before_raising(tmp_path) -> None:
    plugin = get_plugin("metatranscriptomics")
    config = plugin.load_config(overrides={"outdir": str(tmp_path / "results")})
    plan = plugin.build_plan(config)
    fake_bin = _fake_snakemake(tmp_path, exit_code=3)
    runtime = SnakemakeRuntime(
        plugin,
        options=RuntimeOptions(engine="snakemake", smoke=True, snakemake_bin=fake_bin),
    )

    with pytest.raises(ABIError, match="Snakemake run failed with exit code 3"):
        runtime.run(plan, config)

    # Provenance was written BEFORE the raise / 失败时也先写溯源再抛错
    commands_tsv = (tmp_path / "results" / "provenance" / "commands.tsv").read_text(
        encoding="utf-8"
    )
    assert "failed" in commands_tsv
    assert "Snakemake rule failed" in commands_tsv
    assert (tmp_path / "results" / "execution_plan.json").exists()
    assert (tmp_path / "results" / "snakemake" / "snakemake.stderr.log").exists()


def test_snakemake_run_marks_steps_with_done_markers_as_success(tmp_path) -> None:
    plugin = get_plugin("metatranscriptomics")
    config = plugin.load_config(overrides={"outdir": str(tmp_path / "results")})
    plan = plugin.build_plan(config)
    dag = infer_dag(plan.steps, sequential_fallback=True)
    marker_dir = marker_dir_for(config, plan)
    marker_dir.mkdir(parents=True)
    (marker_dir / f"{dag.bindings[0].process_name}.done").touch()

    rows = _command_rows(
        plan,
        plugin.registry(),
        SnakemakeExporter(),
        dag=dag,
        return_code=1,
        smoke=True,
        marker_dir=marker_dir,
        dry_run=False,
    )

    assert rows[0]["status"] == "success"
    assert rows[0]["return_code"] == 0
    assert all(row["status"] == "failed" for row in rows[1:])


def test_snakemake_runtime_forwards_resource_options_to_exporter(tmp_path) -> None:
    plugin = get_plugin("metatranscriptomics")
    config = plugin.load_config(overrides={"outdir": str(tmp_path / "results")})
    plan = plugin.build_plan(config)
    options = RuntimeOptions(
        engine="snakemake",
        smoke=True,
        cpu_override=7,
        memory_override="23GB",
        walltime_override="05:00:00",
    )
    runtime = SnakemakeRuntime(plugin, options=options)

    result = runtime.dry_run(plan, config)
    script = result.outputs["snakefile"].read_text(encoding="utf-8")

    assert "threads: 7" in script
    assert "mem_mb=23552" in script
    assert "runtime=300" in script


