@pytest.mark.requires_tools
def test_snakemake_runtime_end_to_end_smoke_with_real_snakemake(tmp_path) -> None:
    """End-to-end: real snakemake executes the smoke Snakefile (skipped in CI)."""
    if shutil.which("snakemake") is None:
        pytest.skip("snakemake binary not installed")
    plugin = get_plugin("metatranscriptomics")
    config = plugin.load_config(overrides={"outdir": str(tmp_path / "results")})
    plan = plugin.build_plan(config)
    runtime = SnakemakeRuntime(plugin, options=RuntimeOptions(engine="snakemake", smoke=True))

    result = runtime.run(plan, config)

    assert result.status == "success"
    marker_dir = marker_dir_for(config, plan)
    assert any(marker_dir.glob("*.done"))
