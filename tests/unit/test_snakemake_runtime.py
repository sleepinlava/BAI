def _fake_snakemake(tmp_path: Path, *, exit_code: int = 0) -> Path:
    fake_bin = tmp_path / "fake_snakemake"
    fake_bin.write_text(f"#!/bin/sh\nexit {exit_code}\n", encoding="utf-8")
    fake_bin.chmod(0o755)
    return fake_bin


def test_resolve_snakemake_bin_from_option(tmp_path: Path) -> None:
    fake_bin = _fake_snakemake(tmp_path)
    result = resolve_snakemake_bin(fake_bin)
    assert result == fake_bin.resolve()


def test_resolve_snakemake_bin_from_env_var(tmp_path: Path, monkeypatch) -> None:
    fake_bin = _fake_snakemake(tmp_path)
    monkeypatch.setenv("ABI_SNAKEMAKE_BIN", str(fake_bin))
    result = resolve_snakemake_bin(snakemake_bin=None)
    assert result == fake_bin.resolve()


def test_resolve_snakemake_bin_shutil_which_fallback(monkeypatch) -> None:
    monkeypatch.delenv("ABI_SNAKEMAKE_BIN", raising=False)
    monkeypatch.setattr(
        shutil,
        "which",
        lambda name: "/usr/local/bin/snakemake" if name == "snakemake" else None,
    )
    with (
        patch("pathlib.Path.exists", return_value=True),
        patch("os.access", return_value=True),
    ):
        result = resolve_snakemake_bin(snakemake_bin=None)
        assert result.name == "snakemake"


def test_resolve_snakemake_bin_no_binary_found_raises(monkeypatch) -> None:
    monkeypatch.setattr(shutil, "which", lambda name: None)
    monkeypatch.delenv("ABI_SNAKEMAKE_BIN", raising=False)
    with patch("pathlib.Path.exists", return_value=False):
        with pytest.raises(ABIError, match="Snakemake executable was not found"):
            resolve_snakemake_bin(snakemake_bin=None)


